const rub = new Intl.NumberFormat("ru-RU")

export function formatPrice(row: PriceRow) {
  if (row.price === null) return "по запросу"
  return `${row.from ? "от " : ""}${rub.format(row.price)} ₽`
}

export function minPrice(category: ServiceCategory) {
  const known = category.rows.map((r) => r.price).filter((p): p is number => p !== null)
  return known.length ? Math.min(...known) : null
}

